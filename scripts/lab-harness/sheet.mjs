// Render a contact-sheet HTML file to PNG. node sheet.mjs in.html out.png [width]
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { SHOTS } from './paths.mjs';
const [inp, out, width = '1600'] = process.argv.slice(2);
const profile = mkdtempSync(join(SHOTS, 'chrome-sheet-'));
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--remote-debugging-port=0', `--user-data-dir=${profile}`, 'about:blank'], { stdio: ['ignore', 'ignore', 'pipe'] });
const wsUrl = await new Promise((res) => { let buf = ''; chrome.stderr.on('data', (d) => { buf += d; const m = buf.match(/DevTools listening on (ws:\/\/\S+)/); if (m) res(m[1]); }); });
const ws = new WebSocket(wsUrl); await new Promise((r) => ws.addEventListener('open', r, { once: true }));
let id = 1; const pend = new Map();
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } });
const send = (method, params = {}, sessionId) => new Promise((r) => { const i = id++; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params, sessionId })); });
const { targetId } = await send('Target.createTarget', { url: 'file://' + resolve(inp) });
const { sessionId: s } = await send('Target.attachToTarget', { targetId, flatten: true });
await send('Emulation.setDeviceMetricsOverride', { width: Number(width), height: 600, deviceScaleFactor: 1, mobile: false }, s);
await new Promise((r) => setTimeout(r, 800));
const { result } = await send('Runtime.evaluate', { expression: 'document.documentElement.scrollHeight', returnByValue: true }, s);
await send('Emulation.setDeviceMetricsOverride', { width: Number(width), height: result.value, deviceScaleFactor: 1, mobile: false }, s);
await new Promise((r) => setTimeout(r, 300));
const { data } = await send('Page.captureScreenshot', { format: 'png' }, s);
writeFileSync(out, Buffer.from(data, 'base64'));
chrome.kill(); process.exit(0);
